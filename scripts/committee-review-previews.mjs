import assert from "node:assert/strict";
import {resolve} from "node:path";
export async function checkCommitteeReview({browser,url,screenshots}){
 const page=await browser.newPage({viewport:{width:1366,height:768}}),errors=[];page.on("pageerror",error=>errors.push(error.message));
 await page.goto(url+"?view=admin");
 await page.getByRole("button",{name:"Forward to CRECOM",exact:true}).click();
 await page.getByLabel("Synthetic Reviewer 1").check();await page.getByLabel("Synthetic Reviewer 2").check();
 await page.getByRole("button",{name:"Review action",exact:true}).click();
 await page.getByRole("alert").filter({hasText:"exactly 3"}).waitFor();
 await page.getByLabel("Synthetic Reviewer 2").uncheck();
 await page.getByLabel("Synthetic Reviewer 3").check();await page.getByLabel("Synthetic Reviewer 4").check();
 await page.getByRole("button",{name:"Review action",exact:true}).click();
 await page.getByRole("alert").filter({hasText:"two CRECOM members and one CRECOM chairperson"}).waitFor();
 await page.getByLabel("Synthetic Reviewer 4").uncheck();await page.getByLabel("Synthetic Reviewer 2").check();
 assert.equal(await page.getByLabel("Synthetic Reviewer 4").isDisabled(),true);
 await page.getByRole("button",{name:"Review action",exact:true}).click();
 await page.evaluate(()=>{window.reviewFailure=true;});
 await page.getByRole("button",{name:"Confirm review action"}).click();
 await page.getByRole("alert").filter({hasText:"Synthetic review"}).waitFor();
 await page.evaluate(()=>{window.reviewFailure=false;});
 await page.getByRole("button",{name:"Confirm review action"}).click();
 await page.getByRole("table").waitFor();
 const forwards=await page.evaluate(()=>window.reviewCalls.filter(item=>item.operation==="forward"));
 assert.equal(forwards.length,2);assert.equal(forwards[0].requestId,forwards[1].requestId);assert.equal(forwards[1].payload.reviewers.length,3);
 assert.equal(forwards[1].payload.bodRequired,true);
 await page.screenshot({path:resolve(screenshots,"admin-review-progress.png")});
 await page.getByRole("button",{name:"Reassign",exact:true}).nth(2).click();
 const replacement=page.getByRole("dialog").getByRole("combobox");
 assert.deepEqual(await replacement.locator("option").allTextContents(),["Choose the same approval position","Synthetic Reviewer 4 · CRECOM Chairperson"]);
 await page.getByRole("dialog").getByRole("button",{name:"Cancel",exact:true}).click();
 await page.goto(url+"?view=reviewer");
 await page.getByRole("button",{name:"Approve this packet",exact:true}).click();
 await page.getByRole("button",{name:"Record my decision"}).click();
 await page.getByRole("alert").filter({hasText:"Confirm your decision"}).waitFor();
 await page.getByLabel(/I reviewed packet v1/).check();
 await page.getByLabel("Your account password",{exact:true}).fill("Synthetic-Password1!");
 await page.evaluate(()=>{window.reviewFailure=true;});
 await page.getByRole("button",{name:"Record my decision"}).click();
 await page.getByRole("alert").filter({hasText:"Synthetic review"}).waitFor();
 assert.equal(await page.getByLabel("Your account password",{exact:true}).inputValue(),"");
 await page.evaluate(()=>{window.reviewFailure=false;});
 await page.getByLabel("Your account password",{exact:true}).fill("Synthetic-Password1!");
 await page.getByRole("button",{name:"Record my decision"}).click();
 await page.getByRole("heading",{name:"My recorded confirmation"}).waitFor();
 assert.equal(await page.getByRole("button",{name:"Approve this packet",exact:true}).count(),0);
 const votes=await page.evaluate(()=>window.reviewCalls.filter(item=>item.operation==="approve"));
 assert.equal(votes[0].requestId,votes[1].requestId);assert.equal(votes[1].payload.confirmed,true);
 await page.screenshot({path:resolve(screenshots,"reviewer-confirmation-record.png")});
 await page.goto(url+"?view=reviewer");
 await page.getByRole("button",{name:"Reject this packet",exact:true}).click();
 await page.getByRole("button",{name:"Record my decision"}).click();
 await page.getByRole("alert").filter({hasText:"reason or clarification"}).waitFor();
 await page.keyboard.press("Escape");
 await page.getByRole("button",{name:"Request clarification",exact:true}).click();
 await page.getByLabel("Clarification needed",{exact:true}).fill("Please explain the payment projection.");
 await page.getByLabel("Your account password",{exact:true}).fill("Synthetic-Password1!");
 await page.getByRole("button",{name:"Confirm request"}).click();
 await page.getByRole("heading",{name:"My clarification history"}).waitFor();
 assert.equal(await page.getByRole("button",{name:"Approve this packet",exact:true}).isDisabled(),true);
 await page.addInitScript(()=>{window.reviewFinalReady=true;});
 await page.goto(url+"?view=admin");
 await page.getByRole("button",{name:"View confirmation",exact:true}).last().click();
 await page.getByRole("heading",{name:"Recorded committee confirmation"}).waitFor();
 assert.match(await page.getByRole("dialog").innerText(),/BOD Chairperson/);
 assert.match(await page.getByRole("dialog").innerText(),/personal account password/);
 await page.screenshot({path:resolve(screenshots,"admin-bod-confirmation.png")});
 await page.getByRole("dialog").getByRole("button",{name:"Close",exact:true}).click();
 await page.getByRole("button",{name:"Record final decision",exact:true}).click();
 await page.getByRole("dialog").getByRole("combobox").selectOption("approve");
 await page.getByLabel("Reason",{exact:true}).fill("All required confirmations checked.");
 await page.getByRole("button",{name:"Review action",exact:true}).click();
 await page.getByRole("button",{name:"Confirm final decision",exact:true}).click();
 await page.getByRole("alert").filter({hasText:"account password"}).waitFor();
 await page.getByLabel("Your account password",{exact:true}).fill("Synthetic-Password1!");
 await page.getByRole("button",{name:"Confirm final decision",exact:true}).click();
 await page.getByText("Final approval recorded",{exact:true}).waitFor();
 await page.goto(url+"?view=policy");
 await page.getByLabel(/All assigned reviewers must respond/).check();
 await page.getByLabel(/I checked this saved configuration/).check();
 await page.getByRole("button",{name:"Review policy activation",exact:true}).click();
 await page.getByLabel("Your Super Admin password",{exact:true}).fill("Synthetic-Password1!");
 await page.getByRole("button",{name:"Activate this policy",exact:true}).click();
 await page.waitForFunction(()=>window.reviewCalls.some(item=>item.operation==="activate_policy"));
 const activation=await page.evaluate(()=>window.reviewCalls.find(item=>item.operation==="activate_policy"));
 assert.equal(activation.rules.bodReviewers,1);assert.equal(activation.rules.bodApprovals,1);assert.equal(activation.rules.signatoryLayout,"manual_form_v1");assert.equal(activation.rules.crecomApprovals,3);assert.equal(activation.rules.finalMode,"authorized_admin");assert.equal(activation.rules.allowOverride,false);
 await page.addInitScript(()=>{window.reviewBodPending=true;});
 await page.goto(url+"?view=policy");
 assert.equal(await page.getByRole("button",{name:"Review policy activation",exact:true}).isDisabled(),true);
 await page.addInitScript(()=>{window.reviewStale=true;});
 await page.goto(url+"?view=reviewer");
 assert.equal(await page.getByRole("button",{name:"Approve this packet",exact:true}).isDisabled(),true);
 await page.setViewportSize({width:390,height:844});
 await page.getByRole("button",{name:"Recuse",exact:true}).click();
 await page.screenshot({path:resolve(screenshots,"reviewer-confirmation-mobile.png")});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true);
 assert.deepEqual(errors,[]);await page.close();
 console.log("PASS: reviewer selection, retry safety, personal password/acknowledgment, immutable confirmation display, clarification pause, Super Admin final decision, pending BOD gate and mobile layout.");
}
