import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

export async function checkActiveLoans({ browser, url }) {
  const directory = resolve('docs/active-loans-qa');
  mkdirSync(directory, { recursive: true });
  const metrics = [];
  for (const viewport of [{ width: 1536, height: 864 }, { width: 1366, height: 768 }, { width: 768, height: 1024 }, { width: 390, height: 844 }]) {
    const context = await browser.newContext({ viewport, locale: 'en-PH', timezoneId: 'Asia/Manila', acceptDownloads: true });
    await context.route('**/*', route => new URL(route.request().url()).origin === new URL(url).origin ? route.continue() : route.abort());
    const page = await context.newPage();
    await page.emulateMedia({reducedMotion:'reduce'});
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${url}/?active-loans`);
    const table = page.getByRole('table');
    await table.getByRole('button', { name: 'Open actions for APP-PAID', exact: true }).waitFor();
    const row = id => table.getByRole('row').filter({ has: page.getByRole('button', { name: `Open actions for ${id}`, exact: true }) });
    const status = page.getByRole('combobox', { name: 'Filter by status', exact: true });
    const types = page.getByRole('combobox', { name: 'Filter by loan type', exact: true });
    const members = page.getByRole('combobox', { name: 'Filter by membership type', exact: true });
    const search = page.getByRole('searchbox');
    assert.deepEqual(await status.locator('option').allTextContents(), ['All Status', 'Released', 'Overdue', 'Paid', 'Fully Paid']);
    assert.equal(await page.locator('input[type="date"]').count(), 0);
    for (const name of ['Clear', 'Refresh', 'Export CSV']) assert.equal(await page.getByRole('button', { name, exact: true }).count(), 0);
    assert.equal(await search.getAttribute('placeholder'), 'Search name or Member ID...');
    assert.equal(await table.getByRole('columnheader',{name:/Repayment progress/}).count(),0);
    assert.equal(await table.getByRole('progressbar').count(),0,'progress is available from the row menu instead of crowding the table');
    const snapshot = async name => {
      await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
      const measure = await page.evaluate(() => {
        const toolbar = document.querySelector('.ui-toolbar');
        const controls = [...toolbar.querySelectorAll('input,select,button')].map(el => ({ label: el.getAttribute('aria-label') ?? el.textContent, top: el.getBoundingClientRect().top }));
        return { pageOverflow: document.documentElement.scrollWidth > innerWidth, controls };
      });
      assert.equal(measure.pageOverflow, false, 'the page has no horizontal overflow; the table scrolls in its own region');
      if (viewport.width >= 1024) assert.ok(measure.controls.every(control => Math.abs(control.top - measure.controls[0].top) < 2), 'desktop search, filters and export share one row');
      metrics.push({ name, viewport, ...measure });
      await page.screenshot({ path: resolve(directory, `${name}-${viewport.width}.png`), fullPage: true });
    };
    await snapshot('initial');
    const initialUrl=page.url();
    const headers=await table.getByRole('columnheader').allTextContents();
    await members.selectOption('Regular Member');
    await row('APP-RELEASED').waitFor();
    await row('APP-PARTIAL').waitFor();
    assert.equal(await row('APP-PAID').count(),0,'associate loans are excluded from the regular-member filter');
    const regularLabels=table.locator('tbody td:nth-child(2) > p:last-child');
    assert.ok((await regularLabels.allTextContents()).every(label=>label==='Regular Member'));
    assert.equal(await regularLabels.first().evaluate(el=>getComputedStyle(el).backgroundColor),'rgba(0, 0, 0, 0)');
    assert.equal(await regularLabels.first().evaluate(el=>getComputedStyle(el).color),'rgb(100, 116, 139)');
    assert.deepEqual(await table.getByRole('columnheader').allTextContents(),headers,'membership filters keep the Active Loans table');
    assert.equal(page.url(),initialUrl,'filtering does not navigate to a different page');
    await snapshot('regular-members');
    await members.selectOption('Associate Member');
    await row('APP-PAID').waitFor();
    assert.equal(await row('APP-RELEASED').count(),0);
    const associateLabels=table.locator('tbody td:nth-child(2) > p:last-child');
    assert.ok((await associateLabels.allTextContents()).every(label=>label==='Associate Member'));
    assert.equal(await associateLabels.first().evaluate(el=>getComputedStyle(el).backgroundColor),'rgba(0, 0, 0, 0)');
    assert.equal(await associateLabels.first().evaluate(el=>getComputedStyle(el).color),'rgb(100, 116, 139)');
    assert.deepEqual(await table.getByRole('columnheader').allTextContents(),headers);
    await snapshot('associate-members');
    await members.selectOption('All Members');
    await checkRepaymentDialog(page,directory,viewport);
    await page.getByRole('button', { name: 'Next page', exact: true }).click();
    assert.equal(await page.getByRole('navigation', { name: 'Active loans pagination' }).getByRole('button', {name:'Page 2',exact:true}).getAttribute('aria-current'), 'page');
    await status.selectOption('Paid');
    assert.equal(await table.locator('tbody tr').count(), 3, 'changing filters resets pagination');
    await types.selectOption('Emergency'); await members.selectOption('Associate Member');
    assert.equal(await table.locator('tbody tr').count(), 1);
    await search.fill('CSUCC-2026-0002');
    await row('APP-PAID').waitFor();
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Export', exact: true }).click();
    const download = await downloadPromise;
    const csv = readFileSync(await download.path(), 'utf8');
    assert.ok(csv.includes('APP-PAID') && !csv.includes('APP-OVERDUE'));
    assert.ok(csv.includes('"Months Paid"') && csv.includes('"3 of 12 months paid"'));
    await snapshot('filtered-paid');
    await search.fill('No Such Member');
    await page.getByText('No matching loans.', { exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Export', exact: true }).isDisabled(), true);
    await page.getByRole('button', { name: 'Clear filters', exact: true }).click();
    await status.selectOption('Overdue');
    assert.equal(await table.locator('tbody tr').count(), 1);
    await row('APP-OVERDUE').waitFor();
    await status.selectOption('Fully Paid');
    assert.ok((await row('APP-FULL').innerText()).includes('Fully Paid'));
    await page.getByRole('button', { name: 'Open actions for APP-FULL', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Repayment details', exact: true }).waitFor();
    if(viewport.width<1120){
      await page.getByRole('region',{name:'Active loans table',exact:true}).evaluate(el=>{el.scrollLeft=Math.max(0,el.scrollLeft-80);});
      await page.getByRole('menu').waitFor({state:'detached'});
      await page.getByRole('button', { name: 'Open actions for APP-FULL', exact: true }).click();
      await page.getByRole('menuitem', { name: 'Repayment details', exact: true }).waitFor();
    }
    await page.keyboard.press('Escape');
    await status.selectOption('Paid');
    await page.getByRole('button', { name: 'Open actions for APP-PAID', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Record payment', exact: true }).click();
    await page.getByRole('heading', { name: 'Record payment', exact: true }).waitFor();
    assert.equal(await page.evaluate(() => window.rpcCalls.find(call => call.name === 'loan_payment_ledger').args.p_loan_id), 'loan-paid');
    await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
    const loads = await page.evaluate(() => window.activeLoads);
    await page.evaluate(() => {
      const loan = window.syntheticActiveLoans.find(loan => loan.id === 'loan-paid');
      loan.progress.monthsPaid = 4;
      loan.progress.principalPaid = 4000;
      window.realtimeSubscriptions.find(item => item.filter.table === 'loan_payments').callback();
    });
    await page.waitForFunction(previous => window.activeLoads > previous, loads);
    await page.waitForFunction(()=>window.activeLoads>1);
    assert.equal(await table.getByRole('progressbar').count(),0);
    assert.deepEqual(errors, []);
    await context.close();
  }
  const context = await browser.newContext();
  const page = await context.newPage();
  await page.addInitScript(() => { window.testRole = 'admin'; window.activeLoansFailure = true; });
  await page.goto(`${url}/?active-loans`);
  await page.getByRole('alert').waitFor();
  assert.equal(await page.getByRole('button', { name: 'Export', exact: true }).isDisabled(), true);
  await page.evaluate(() => { window.activeLoansFailure = false; });
  await page.getByRole('button', { name: 'Retry', exact: true }).click();
  await page.getByRole('button', { name: 'Open actions for APP-PAID', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Open actions for APP-PAID', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Repayment details', exact: true }).click();
  await page.getByRole('heading', { name: 'Repayment Details', exact: true }).waitFor();
  await page.getByText('OR-NOV-001',{exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Record payment',exact:true}).count(),0);
  assert.equal(await page.getByRole('button',{name:'Reverse payment',exact:true}).count(),0);
  await context.close();
  const operations=await browser.newContext({viewport:{width:1366,height:768}});
  const actionPage=await operations.newPage();
  await actionPage.emulateMedia({reducedMotion:'reduce'});
  await actionPage.addInitScript(()=>{
    window.repaymentLoadFailure=true;
    window.repaymentPayments=Array.from({length:12},(_,i)=>({id:'paged-'+i,receipt_number:'OR-PAGED-'+i,payment_status:'posted',payment_amount:100,principal_amount:100,interest_amount:0,penalty_amount:0,fee_amount:0,payment_date:'2026-11-08',created_at:i===0?null:'2026-11-10T06:30:45Z',payment_method:'cash',recorded_by:'synthetic-staff',recorded_by_name:'Test Cashier',reversal_reason:null,reversed_at:null,notes:null}));
  });
  await actionPage.goto(`${url}/?active-loans`);
  await actionPage.getByRole('button',{name:'Open actions for APP-PAID',exact:true}).click();
  await actionPage.getByRole('menuitem',{name:'Repayment details',exact:true}).click();
  await actionPage.getByRole('alert').waitFor();
  await actionPage.evaluate(()=>{window.repaymentLoadFailure=false;});
  await actionPage.getByRole('button',{name:'Retry',exact:true}).click();
  await actionPage.getByText('OR-PAGED-0',{exact:true}).waitFor();
  await actionPage.getByText('Time not recorded',{exact:true}).waitFor();
  const paymentPages=actionPage.getByRole('navigation',{name:'Payment history pagination',exact:true});
  await paymentPages.getByRole('button',{name:'Next page',exact:true}).click();
  assert.ok((await paymentPages.innerText()).includes('Page 2 of 2'));
  await actionPage.getByRole('button',{name:'Reverse payment',exact:true}).first().click();
  const reverse=actionPage.getByRole('button',{name:'Confirm reversal',exact:true});
  assert.equal(await reverse.isDisabled(),true);
  await actionPage.getByLabel('Reason',{exact:true}).fill('Synthetic duplicate receipt');
  await actionPage.evaluate(()=>{window.financialFailure=true;});
  await reverse.click();
  await actionPage.getByRole('dialog').last().getByRole('alert').waitFor();
  assert.equal(await actionPage.getByRole('heading',{name:'Payment records updated',exact:true}).count(),0);
  await actionPage.evaluate(()=>{window.financialFailure=false;});
  await reverse.evaluate(button=>{button.click();button.click();});
  await actionPage.getByRole('heading',{name:'Payment records updated',exact:true}).waitFor();
  await actionPage.getByRole('button',{name:'OK',exact:true}).click();
  assert.equal(await actionPage.evaluate(()=>window.rpcCalls.filter(call=>call.name==='reverse_counter_payment').length),2,'failed attempt plus one successful reversal; duplicate clicks stay blocked');
  await actionPage.getByRole('tab',{name:'Monthly Summary',exact:true}).click();
  const revised=actionPage.getByRole('article',{name:'November 2026'});
  assert.ok((await revised.innerText()).includes('₱1,100.00'));
  assert.ok((await revised.innerText()).includes('11 posted receipts · 1 reversed'));
  await operations.close();
  writeFileSync(resolve(directory, 'metrics.json'), JSON.stringify(metrics, null, 2));
  console.log('PASS: Clean loan table, Repayment Details, monthly totals, Philippine timestamps, receipt history, filters, CSV, live refresh, nested payment entry, reversals, retry, pagination, and permissions at four screen sizes. Synthetic data only.');
}

async function checkRepaymentDialog(page,directory,viewport) {
  await page.getByRole('button',{name:'Open actions for APP-PAID',exact:true}).click();
  await page.getByRole('menuitem',{name:'Repayment details',exact:true}).click();
  await page.getByRole('heading',{name:'Repayment Details',exact:true}).waitFor();
  await page.getByText('OR-NOV-001',{exact:true}).waitFor();
  const dialog=page.getByRole('dialog').last();
  assert.equal(await dialog.getByRole('progressbar').getAttribute('aria-valuenow'),'3');
  const history=dialog.getByRole('region',{name:'Payment history',exact:true}).getByRole('table');
  const receipt=history.getByRole('row').filter({has:page.getByText('OR-NOV-001',{exact:true})});
  assert.ok((await receipt.innerText()).includes('November 8, 2026'));
  assert.ok((await receipt.innerText()).includes('Nov 10, 2026'));
  assert.ok((await receipt.innerText()).includes('2:30:45'));
  assert.ok((await receipt.innerText()).includes('PHT'));
  assert.ok((await receipt.innerText()).includes('₱1,600.00'));
  const snapshot=async name=>{
    const measurement=await dialog.evaluate(el=>{const rect=el.getBoundingClientRect(),footer=el.querySelector('.ui-dialog-footer').getBoundingClientRect();return {bounded:rect.x>=0&&rect.y>=0&&rect.right<=innerWidth&&rect.bottom<=innerHeight,overflow:el.scrollWidth>el.clientWidth,footerVisible:footer.bottom<=innerHeight};});
    assert.ok(measurement.bounded&&!measurement.overflow&&measurement.footerVisible,`${name}: ${JSON.stringify(measurement)}`);
    await page.screenshot({path:resolve(directory,`${name}-${viewport.width}.png`)});
  };
  await snapshot('repayment-history');
  await dialog.getByRole('tab',{name:'Monthly Summary',exact:true}).click();
  const november=dialog.getByRole('article',{name:'November 2026'});
  assert.ok((await november.innerText()).includes('₱2,600.00'));
  assert.ok((await november.innerText()).includes('2 posted receipts · 1 reversed'));
  assert.ok((await dialog.getByRole('article',{name:'October 2026'}).innerText()).includes('₱1,000.00'));
  await snapshot('monthly-summary');
  await dialog.getByRole('button',{name:'View October 2026 receipts',exact:true}).click();
  assert.equal(await history.locator('tbody tr').count(),1);
  await page.getByText('OR-OCT-001',{exact:true}).waitFor();
  await dialog.getByRole('combobox',{name:'Filter payment history by month'}).selectOption('all');
  await dialog.getByRole('button',{name:'Record payment',exact:true}).click();
  const entry=page.getByRole('dialog').last();
  await entry.getByRole('heading',{name:'Record payment',exact:true}).waitFor();
  assert.equal(await entry.getByRole('region',{name:'Payment history',exact:true}).count(),0,'payment entry no longer duplicates history');
  await page.getByLabel('Official receipt number').fill('OR-DETAILS-TEST');
  await page.getByLabel('Amount paid').fill('100.00');
  await page.screenshot({path:resolve(directory,`record-payment-${viewport.width}.png`)});
  await page.getByRole('button',{name:'Review payment',exact:true}).click();
  await page.getByRole('button',{name:'Confirm and record',exact:true}).click();
  await page.getByRole('heading',{name:'Payment records updated',exact:true}).waitFor();
  await page.getByRole('button',{name:'OK',exact:true}).click();
  await entry.getByRole('button',{name:'Close',exact:true}).click();
  await dialog.getByText('OR-DETAILS-TEST',{exact:true}).waitFor();
  await dialog.getByRole('button',{name:'Close',exact:true}).click();
}
