import assert from 'node:assert/strict';
import {resolve} from 'node:path';
export async function checkDocuments({browser,url,screenshots}){
 const page=await browser.newPage({viewport:{width:1366,height:900}});const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto(url);await page.getByRole('button',{name:'Documents',exact:true}).click();
 await page.waitForTimeout(500);
 if(errors.length)throw new Error(errors.join('\n'));
 await page.getByRole('region',{name:'Member document submissions'}).waitFor();
 assert.equal(await page.getByRole('table').locator('tbody tr').count(),10);
 const nav=page.getByRole('navigation',{name:'Member documents pagination'});
 await nav.getByRole('button',{name:/Next/}).click();assert.equal(await nav.locator('[aria-current="page"]').textContent(),'2');
 await page.getByLabel('Search member documents',{exact:true}).fill('Maria Cruz');
 assert.equal(await page.getByRole('table').locator('tbody tr').count(),1);
 await page.screenshot({path:resolve(screenshots,'documents-member-search.png'),fullPage:true});
 await page.getByRole('button',{name:/Review documents for Synthetic Maria/}).click();
 await page.getByRole('button',{name:'Needs replacement',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'Save replacement request',exact:true}).isDisabled(),true);
 await page.getByRole('textbox',{name:/Reason/}).fill('The ID photo is blurred. Please upload a clear copy.');
 await page.getByRole('button',{name:'Save replacement request',exact:true}).click();
 await page.getByText('The ID photo is blurred. Please upload a clear copy.',{exact:true}).first().waitFor();
 await page.screenshot({path:resolve(screenshots,'documents-review.png'),fullPage:true});
 await page.getByRole('tab',{name:'Shared Documents'}).click();
 await page.getByLabel('Filter shared document audience').selectOption('all-members');assert.equal(await page.getByRole('table').locator('tbody tr').count(),1);
 await page.getByRole('button',{name:'Upload document',exact:true}).click();
 await page.getByRole('textbox',{name:/Document title/}).fill('Targeted checklist');
 await page.getByLabel('Selected members',{exact:true}).check();
 await page.getByRole('textbox',{name:'Find a member by name or ID'}).fill('Maria Cruz');
 await page.getByRole('button',{name:/Synthetic Maria Cruz CSUCC-TEST-1/}).click();
 await page.locator('input[type=file]').setInputFiles({name:'checklist.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.7\nSynthetic test')});
 await page.getByRole('button',{name:'Review sharing',exact:true}).click();
 await page.getByText('Selected recipients (1)',{exact:true}).waitFor();
 await page.screenshot({path:resolve(screenshots,'documents-recipient-confirmation.png'),fullPage:true});
 await page.getByRole('button',{name:'Publish document',exact:true}).evaluate(el=>{el.click();el.click();});
 await page.getByRole('heading',{name:'Document updated',exact:true}).waitFor();
 assert.equal(await page.evaluate(()=>window.documentCalls.filter(item=>item.body instanceof FormData).length),1);
 await page.keyboard.press('Escape');await page.getByText('Targeted checklist',{exact:true}).waitFor();
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:resolve(screenshots,'documents-mobile.png'),fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);await page.close();
 console.log('PASS: document search, paging, review reason/history, audience filtering, recipient confirmation, duplicate submission guard and mobile layout.');
}
