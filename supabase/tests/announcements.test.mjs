// Runs the real migration in an isolated, in-memory PostgreSQL runtime.
// The optional test runtime is installed outside the app; never point this at a live DB.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const loadModule = createRequire(import.meta.url);
const { PGlite } = loadModule(process.env.ANNOUNCEMENT_PG_MODULE || '@electric-sql/pglite');
const testDirectory = fileURLToPath(new URL('.',import.meta.url));
const ids = { super: '11111111-1111-4111-8111-111111111111', admin: '22222222-2222-4222-8222-222222222222', member: '33333333-3333-4333-8333-333333333333', inactive: '44444444-4444-4444-8444-444444444444', blocked: '55555555-5555-4555-8555-555555555555' };
const first = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa', second = 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb', third = 'cccccccc-cccc-4ccc-8ccc-cccccccccccc';
(async () => {
  const db = new PGlite();
  const checks = [];
  const query = async (sql, args = []) => (await db.query(sql, args)).rows;
  const login = async (id) => { await db.exec('RESET ROLE'); await query("SELECT set_config('request.jwt.claims',$1,false)", [JSON.stringify({ sub: id })]); await db.exec('SET ROLE authenticated'); };
  const owner = () => db.exec('RESET ROLE');
  const current = async (id) => (await query('SELECT * FROM public.announcements WHERE id=$1', [id]))[0];
  const save = async (id, version, payload) => query("SELECT public.manage_announcement('save',$1,$2,$3::jsonb)", [id, version, JSON.stringify(payload)]);
  const action = async (name, id) => query('SELECT public.manage_announcement($1,$2,$3,$4::jsonb)', [name, id, (await current(id)).updated_at, '{}']);
  const payload = (status, notify = false) => ({ title: 'Isolated announcement', content: 'Cooperative information', category_id: 'general', status, scheduled_at: status === 'scheduled' ? '2099-01-01T04:00:00Z' : null, notify_members: notify });
  try {
    await db.exec(`
      CREATE ROLE anon NOLOGIN;
      CREATE ROLE authenticated NOLOGIN;
      CREATE ROLE service_role NOLOGIN BYPASSRLS;
      CREATE SCHEMA auth;
      CREATE TABLE auth.users(id uuid PRIMARY KEY,raw_app_meta_data jsonb NOT NULL, banned_until timestamptz);
      CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT (current_setting('request.jwt.claims',true)::jsonb ->> 'sub')::uuid $$;
      CREATE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql STABLE AS $$ SELECT current_setting('request.jwt.claims',true)::jsonb $$;
      GRANT USAGE ON SCHEMA auth,public TO authenticated,service_role;
      CREATE TABLE public.members(id uuid DEFAULT gen_random_uuid() PRIMARY KEY,user_id uuid UNIQUE REFERENCES auth.users(id),first_name text,last_name text,status text NOT NULL,role text NOT NULL DEFAULT 'Member',must_change_password boolean NOT NULL DEFAULT false);
      CREATE TABLE public.notifications(id uuid DEFAULT gen_random_uuid() PRIMARY KEY,user_id uuid REFERENCES auth.users(id),title varchar(200) NOT NULL,message text NOT NULL,type text NOT NULL CHECK(type IN('info','success','warning','error','loan_approval','loan_rejection','payment_reminder')),read boolean NOT NULL DEFAULT false,created_at timestamptz DEFAULT now());
      CREATE TABLE public.admin_activity_logs(id uuid DEFAULT gen_random_uuid() PRIMARY KEY,actor_id uuid NOT NULL REFERENCES auth.users(id),action_name text NOT NULL,target_id text NOT NULL,result text NOT NULL,details jsonb NOT NULL,created_at timestamptz DEFAULT now());
    `);
    for (const [name, id] of Object.entries(ids)) await query('INSERT INTO auth.users(id,raw_app_meta_data) VALUES($1,$2::jsonb)', [id, JSON.stringify({ role: name === 'super' || name === 'blocked' ? 'super_admin' : name === 'admin' ? 'admin' : 'member', account_status: name === 'inactive' ? 'inactive' : name === 'blocked' ? 'blocked' : 'active' })]);
    for (const name of ['member','inactive']) await query("INSERT INTO public.members(user_id,first_name,last_name,status) VALUES($1,'Test','Member',$2)", [ids[name], name === 'member' ? 'active' : 'inactive']);
    await db.exec(fs.readFileSync(path.join(testDirectory,'../../../coop_backend/supabase/migrations/024_announcement_management.sql'),'utf8'));
    checks.push('real migration executes successfully');
    await login(ids.super);
    assert.equal((await query('SELECT public.announcement_service_status() AS data'))[0].data.scheduling_enabled,false);
    await assert.rejects(save(first,null,payload('scheduled')), error => error.code === '55000');
    checks.push('scheduling stays disabled without a configured job');
    await save(first,null,payload('draft'));
    assert.equal((await current(first)).status,'draft');
    await assert.rejects(query("UPDATE public.announcements SET title='Bypass' WHERE id=$1",[first]), error => error.code === '42501');
    await login(ids.member);
    assert.equal((await query('SELECT * FROM public.announcements')).length,0);
    assert.equal((await query('SELECT * FROM public.member_announcements')).length,0);
    await assert.rejects(save(second,null,payload('draft')), error => error.code === '42501');
    await assert.rejects(query('SELECT public.publish_due_announcements()'), error => error.code === '42501');
    checks.push('members cannot read drafts, write records or invoke publication workers; direct writes are denied');
    await login(ids.admin);
    assert.equal((await query('SELECT * FROM public.announcements')).length,1);
    await assert.rejects(save(second,null,payload('draft')), error => error.code === '42501');
    await login(ids.blocked);
    assert.equal((await query('SELECT * FROM public.announcements')).length,0);
    await assert.rejects(save(second,null,payload('draft')), error => error.code === '42501');
    checks.push('Admin read-only and blocked-account restrictions are enforced in PostgreSQL');
    await login(ids.super);
    const version = (await current(first)).updated_at;
    await save(first,version,payload('published',true));
    await assert.rejects(save(first,version,payload('published',true)), error => error.code === '40001');
    await save(first,(await current(first)).updated_at,{...payload('published',true),content:'Revised information'});
    await owner();
    assert.equal(Number((await query('SELECT count(*) AS count FROM public.notifications'))[0].count),1);
    assert.equal((await query('SELECT user_id FROM public.notifications'))[0].user_id,ids.member);
    assert.equal(Number((await query('SELECT count(*) AS count FROM public.announcement_notification_receipts'))[0].count),1);
    checks.push('publication is persisted, stale edits fail, active members receive exactly one alert and edits do not resend');
    await login(ids.member);
    assert.equal((await query('SELECT * FROM public.member_announcements')).length,1);
    await login(ids.inactive);
    assert.equal((await query('SELECT * FROM public.member_announcements')).length,0);
    await login(ids.super);
    await action('archive',first);
    await login(ids.member);
    assert.equal((await query('SELECT * FROM public.member_announcements')).length,0);
    await login(ids.super);
    await action('restore',first);
    assert.equal((await current(first)).status,'draft');
    await assert.rejects(action('delete',first), error => error.code === 'P0001');
    await save(first,(await current(first)).updated_at,payload('published',true));
    await owner();
    assert.equal(Number((await query('SELECT count(*) AS count FROM public.notifications'))[0].count),1);
    checks.push('archive removes member visibility; restore stays private; published records cannot be deleted; republish deduplicates notifications');
    await db.exec("CREATE SCHEMA cron; CREATE TABLE cron.job(jobname text,active boolean,command text); INSERT INTO cron.job VALUES('csucc_mpc_publish_announcements',true,'SELECT public.publish_due_announcements();');");
    await login(ids.super);
    assert.equal((await query('SELECT public.announcement_service_status() AS data'))[0].data.scheduling_enabled,true);
    await save(second,null,payload('scheduled',true));
    await owner();
    assert.equal(Number((await query('SELECT count(*) AS count FROM public.notifications'))[0].count),1);
    await query("UPDATE public.announcements SET scheduled_at=now()-interval '1 minute' WHERE id=$1",[second]);
    await db.exec('SET ROLE service_role');
    assert.equal((await query('SELECT public.publish_due_announcements() AS count'))[0].count,1);
    assert.equal((await query('SELECT public.publish_due_announcements() AS count'))[0].count,0);
    await owner();
    assert.equal((await current(second)).status,'published');
    assert.equal(Number((await query('SELECT count(*) AS count FROM public.notifications'))[0].count),2);
    checks.push('due jobs publish once and notify only after publication; repeated worker runs do not duplicate alerts');
    await login(ids.super);
    const rollbackId = 'dddddddd-dddd-4ddd-8ddd-dddddddddddd';
    await save(rollbackId,null,payload('draft'));
    await owner();
    await db.exec("CREATE FUNCTION public.test_reject_notification() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'Isolated delivery failure'; END $$; CREATE TRIGGER test_reject_notification BEFORE INSERT ON public.notifications FOR EACH ROW EXECUTE FUNCTION public.test_reject_notification();");
    await login(ids.super);
    await assert.rejects(save(rollbackId,(await current(rollbackId)).updated_at,payload('published',true)), error => error.code === 'P0001');
    assert.equal((await current(rollbackId)).status,'draft');
    await owner();
    assert.equal(Number((await query('SELECT count(*) AS count FROM public.announcement_notification_receipts WHERE announcement_id=$1',[rollbackId]))[0].count),0);
    assert.equal(Number((await query('SELECT count(*) AS count FROM public.notifications'))[0].count),2);
    await db.exec('DROP TRIGGER test_reject_notification ON public.notifications; DROP FUNCTION public.test_reject_notification();');
    checks.push('failed notification inserts roll back publication and delivery receipts atomically');
    await login(ids.super);
    await save(third,null,payload('scheduled',true));
    await action('cancel_schedule',third);
    assert.equal((await current(third)).status,'draft');
    await action('delete',third);
    assert.equal(await current(third),undefined);
    checks.push('cancel schedule preserves a draft; never-published drafts can be deleted');
    await save(third,null,payload('scheduled',true));
    await owner();
    await query("UPDATE auth.users SET raw_app_meta_data=raw_app_meta_data||'{\"account_status\":\"blocked\"}'::jsonb WHERE id=$1",[ids.super]);
    await query("UPDATE public.announcements SET scheduled_at=now()-interval '1 minute' WHERE id=$1",[third]);
    await db.exec('SET ROLE service_role');
    assert.equal((await query('SELECT public.publish_due_announcements() AS count'))[0].count,0);
    await owner();
    assert.equal((await current(third)).status,'draft');
    assert.equal(Number((await query('SELECT count(*) AS count FROM public.notifications'))[0].count),2);
    assert.ok(Number((await query('SELECT count(*) AS count FROM public.admin_activity_logs'))[0].count)>0);
    assert.ok((await query("SELECT * FROM public.announcement_events WHERE action='schedule_cancelled_author_inactive'")).length>0);
    checks.push('revoked authors cannot publish scheduled posts; audit records persist');
    console.log(JSON.stringify({result:'PASS',checks},null,2));
  } finally { await db.close(); }
})().catch(error=>{ console.error(error);process.exitCode=1; });
